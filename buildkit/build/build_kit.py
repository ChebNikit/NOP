@step("Inno Setup compiler")
def ensure_inno(args):
    spec = lock_components()["signed_downloads"]["innosetup"]
    existing_compiler = _find_iscc()
    if existing_compiler:
        log(f"  using {existing_compiler}")
        return
    existing = _accept_existing_iscc(spec["min_version"])
    if existing:
        os.environ["NOP_ISCC"] = str(existing)
        return
    log("  no installed Inno Setup was detected (PATH, registry, Program Files, Local\\Programs)")
    cached = CACHE / spec["file"]
    problems = []
    if not cached.is_file() and not args.offline:
        try:
            tags = kitlib.fetch_text(spec["version_discovery"], retries=2)
        except KitError as exc:
            tags = ""
            problems.append(str(exc))
        for url in inno_urls(spec, tags):
            try:
                kitlib.download(url, cached, label="Inno Setup", retries=2, user_agent=kitlib.BROWSER_AGENT)
                break
            except KitError as exc:
                problems.append(f"{url}: {exc}")
                cached.unlink(missing_ok=True)
        else:
            if shutil.which("winget"):
                log("  direct download failed; trying winget (JRSoftware.InnoSetup)")
                kitlib.run(["winget", "install", "-e", "--id", spec["winget_id"], "--silent", "--scope", "user",
                            "--accept-package-agreements", "--accept-source-agreements"], check=False, timeout=900)
                existing = _accept_existing_iscc(spec["min_version"])
                if existing:
                    os.environ["NOP_ISCC"] = str(existing)
                    return
    if not cached.is_file():
        raise KitError("Inno Setup could not be obtained automatically.\n"
                       "  Fix (any one):\n"
                       "   1) install it yourself from https://jrsoftware.org/isdl.php (version 6.5.0 or newer, for the current user) and run the build again - it is detected automatically;\n"
                       "   2) or save the downloaded installer as  cache\\innosetup-setup.exe  and run again;\n"
                       "   3) or set the environment variable NOP_ISCC to the full path of ISCC.exe.\n"
                       + "\n".join("  tried: " + line[:200] for line in problems[-6:]))
    _install_inno(cached, spec)
    if not _find_iscc():
        raise KitError("Inno Setup was installed, but ISCC.exe was not found.")
    if not (INNO_DIR / "Languages" / "Russian.isl").is_file():
        raise KitError("Inno Setup has no Russian.isl translation; the installer cannot be built in Russian.")


