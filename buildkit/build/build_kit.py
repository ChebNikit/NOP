@step("Compile NOP_Setup.exe")
def compile_installer(args):
    iscc = _find_iscc()
    if not iscc:
        raise KitError("Inno Setup compiler ISCC.exe was not found. Run step 9 first.")
    template_path = KIT / "installer" / "NOP_Setup.iss.template"
    script = ART / "NOP_Setup.iss"
    log("  refreshing installer artwork")
    refresh_installer_art()  # step 10 must not reuse stale BMPs when resuming with --from-step 10
    (ART / "package_manifest.iss.inc").write_text(installer_package_manifest(), encoding="utf-8-sig")
    write_inno_script(template_path, script)  # Inno needs one UTF-8 BOM for Russian texts
    DIST.mkdir(exist_ok=True)
    defines = [f"/DAppVersion={APP_VERSION}", f"/DPayloadDir={PAYLOAD}", f"/DArtDir={ART}", f"/DOutDir={DIST}"]
    if (PAYLOAD / "converters").is_dir():
        defines.append("/DHasEngines=1")
    redist = _vc_redist(args)
    if redist:
        defines.append(f"/DVcRedist={redist}")
    apo = apo_installer(args)
    apo_spec = lock_components()["installers"]["equalizer_apo"]
    defines += [f"/DApoInstaller={apo}", f"/DApoFile={apo_spec['file']}", f"/DApoVersion={apo_spec['version']}"]
    target = DIST / "NOP_Setup.exe"
    target.unlink(missing_ok=True)
    try:
        kitlib.run([str(iscc), "/Qp", *defines, str(script)], cwd=ART, timeout=14400)
    except KitError as exc:
        hint = ""
        if "2 GB" in str(exc) or "4 GB" in str(exc) or "size" in str(exc).lower():
            hint = ("\nThe installer may exceed Inno Setup's size limit. Build the compact installer with --no-engines "
                    "(without LibreOffice/Inkscape/Calibre/Blender) or report the exact message.")
        raise KitError(str(exc) + hint) from None
    if not target.is_file():
        raise KitError("ISCC finished without producing NOP_Setup.exe.")
    sign = os.environ.get("NOP_SIGN_CMD")
    if sign:
        kitlib.run(["cmd", "/C", sign.replace("$f", f'"{target}"')])
    digest = kitlib.sha256_file(target)
    (DIST / "NOP_Setup.exe.sha256").write_text(f"{digest} *NOP_Setup.exe\n", encoding="ascii")
    log(f"  NOP_Setup.exe  {kitlib.human_size(target.stat().st_size)}  sha256 {digest}")


