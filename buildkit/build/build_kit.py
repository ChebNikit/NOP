@step("Runtime components (mpv, FFmpeg, deno)")
def fetch_components(args):
    lock = lock_components()["components"]
    CACHE.mkdir(exist_ok=True)
    paths = {}
    for name, item in lock.items():
        if args.offline and not (CACHE / item["file"]).is_file():
            raise KitError(f"Offline mode: {item['file']} is missing from the cache folder ({CACHE}).")
        paths[name] = kitlib.download(item["url"], CACHE / item["file"], item["sha256"], item.get("size"), label=f"{name} {item['version']}")
    if COMPONENTS.exists():
        kitlib.rmtree(COMPONENTS)
    apo_installer(args)  # fail early if the Equalizer APO installer cannot be obtained
    seven = paths["7zr"]
    kitlib.extract_7z(seven, paths["libmpv"], COMPONENTS / "libmpv")
    kitlib.safe_extract_zip(paths["ffmpeg"], COMPONENTS / "ffmpeg")
    kitlib.safe_extract_zip(paths["deno"], COMPONENTS / "deno")
    found = {
        "libmpv-2.dll": next((COMPONENTS / "libmpv").rglob("libmpv-2.dll"), None),
        "ffmpeg.exe": next((COMPONENTS / "ffmpeg").rglob("ffmpeg.exe"), None),
        "ffprobe.exe": next((COMPONENTS / "ffmpeg").rglob("ffprobe.exe"), None),
        "deno.exe": next((COMPONENTS / "deno").rglob("deno.exe"), None),
    }
    import pefile
    for name, path in found.items():
        if path is None:
            raise KitError(f"{name} was not found inside the downloaded archive; the component layout changed.")
        pe = pefile.PE(str(path), fast_load=True)
        if pe.FILE_HEADER.Machine != 0x8664:
            raise KitError(f"{name} is not a 64-bit binary.")
        pe.close()
        log(f"  ok  {name:14s} {kitlib.human_size(path.stat().st_size)}")


# ------------------------------------------------------------------ conversion engines
def engine_root(extracted: Path, tool_rel: str) -> Path | None:
    """Folder that contains *tool_rel* (e.g. 'program/soffice.exe') somewhere below *extracted*."""
    parts = Path(tool_rel).parts
    wanted = "/".join(parts).lower()
    hits = [p for p in Path(extracted).rglob(parts[-1]) if "/".join(p.as_posix().lower().split("/")[-len(parts):]) == wanted]
    if not hits:
        return None
    best = min(hits, key=lambda p: len(p.parts))
    root = best
    for _ in parts:
        root = root.parent
    return root


def prune_engine(root: Path, patterns: list[str]) -> None:
    for pattern in patterns:
        for path in Path(root).glob(pattern):
            if path.is_dir():
                kitlib.rmtree(path, ignore_errors=True)
            elif path.is_file():
                path.unlink(missing_ok=True)


def _msi_extract(msi: Path, target: Path) -> None:
    if target.exists():
        kitlib.rmtree(target)
    target.mkdir(parents=True)
    # Administrative install = unpack only: nothing is installed or registered on this machine.
    command = f'msiexec /a "{msi}" /qn /norestart TARGETDIR="{target}"'
    log("  $ " + command)
    result = subprocess.run(command, capture_output=True, text=True, timeout=3600)
    if result.returncode not in (0, 3010):
        raise KitError(f"msiexec could not unpack {Path(msi).name} (exit code {result.returncode}).")


def zip_fallback_urls(msi_url: str, rule: dict) -> tuple[str, str] | None:
    """(zip URL, checksum-list URL) derived from the MSI URL that winget downloaded, or None."""
    if not msi_url or not msi_url.lower().endswith(rule["suffix_from"]):
        return None
    zip_url = msi_url[: -len(rule["suffix_from"])] + rule["suffix_to"]
    folder = msi_url.rsplit("/", 1)[0]
    match = re.search(rule["version_regex"], msi_url.rsplit("/", 1)[1])
    if not match:
        return None
    return zip_url, rule["hash_list"].format(dir=folder, version=match.group(1))


def sha_from_list(text: str, filename: str) -> str | None:
    """SHA-256 for *filename* from a 'hash  name' checksum list (sha256sum / Blender format)."""
    for line in text.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[-1].lstrip("*").lower() == filename.lower() and re.fullmatch(r"[0-9a-fA-F]{64}", parts[0]):
            return parts[0].lower()
    return None


def _winget_download(item: dict, folder: Path) -> tuple[Path, str]:
    if not shutil.which("winget"):
        raise KitError("winget is not available on this machine.")
    if folder.exists():
        kitlib.rmtree(folder)
    folder.mkdir(parents=True)
    result = kitlib.run(["winget", "download", "-e", "--id", item["winget"], "--download-directory", str(folder),
                         "--accept-package-agreements", "--accept-source-agreements", "--skip-dependencies"],
                        check=False, timeout=3600)
    files = [p for p in folder.iterdir() if p.suffix.lower() in {".msi", ".zip", ".exe"}]
    if result.returncode != 0 or not files:
        raise KitError(f"'winget download {item['winget']}' failed (exit code {result.returncode}). "
                       "winget 1.6 or newer is required for 'winget download'.")
    urls = re.findall(r"https?://\S+?\.(?:msi|zip|exe)", result.stdout or "")
    order = {".msi": 0, ".zip": 1, ".exe": 2}
    return sorted(files, key=lambda p: (order[p.suffix.lower()], -p.stat().st_size))[0], (urls[-1] if urls else "")


def _msi_unpack_with_retry(installer: Path, extracted: Path) -> None:
    """Administrative unpack; on failure once more into a short path next to the drive root (long paths break some MSIs)."""
    try:
        _msi_extract(installer, extracted)
        return
    except KitError as first:
        short = Path(os.environ.get("SystemDrive", "C:") + "\\") / "NOPX" / extracted.name
        log(f"  retrying the unpack in a short path: {short}")
        try:
            _msi_extract(installer, short)
        except (KitError, OSError):
            raise first from None
        if extracted.exists():
            kitlib.rmtree(extracted)
        shutil.copytree(short, extracted)
        kitlib.rmtree(short, ignore_errors=True)


def _engine_zip_fallback(name: str, item: dict, msi_url: str) -> Path:
    rule = item.get("zip_fallback")
    derived = zip_fallback_urls(msi_url, rule) if rule else None
    if not derived:
        raise KitError("No portable ZIP is known for this engine.")
    zip_url, hash_url = derived
    filename = zip_url.rsplit("/", 1)[1]
    digest = sha_from_list(kitlib.fetch_text(hash_url), filename)
    if not digest:
        raise KitError(f"{filename} is not listed in {hash_url}; refusing an unverified download.")
    archive = kitlib.download(zip_url, CACHE / "engines" / name / filename, digest, label=filename)
    extracted = WORK / "engine-extract" / (name + "-zip")
    if extracted.exists():
        kitlib.rmtree(extracted)
    kitlib.safe_extract_zip(archive, extracted)
    root = engine_root(extracted, item["tool"])
    if root is None:
        raise KitError(f"{item['tool']} was not found inside {filename}.")
    return root


def _engine_from_winget(name: str, item: dict) -> Path:
    download_dir = CACHE / "engines" / name
    installer, msi_url = _winget_download(item, download_dir)
    digest = kitlib.sha256_file(installer)
    record = CACHE / "engines" / f"{name}.sha256"
    previous = record.read_text().strip() if record.is_file() else ""
    log(f"  {installer.name}  sha256 {digest}" + ("" if not previous or previous == digest else "  (differs from the previously recorded build)"))
    record.write_text(digest)
    if installer.suffix.lower() in {".msi", ".exe"} and os.name == "nt":
        try:
            log("  signed by: " + kitlib.verify_authenticode(installer, item["signer_contains"]))
        except KitError as exc:
            log(f"  WARNING: {exc}")
    extracted = WORK / "engine-extract" / name
    if installer.suffix.lower() == ".msi":
        try:
            _msi_unpack_with_retry(installer, extracted)
        except KitError as exc:
            if not item.get("zip_fallback"):
                raise
            log(f"  MSI unpack failed ({exc}); using the official portable ZIP instead")
            return _engine_zip_fallback(name, item, msi_url)
    elif installer.suffix.lower() == ".zip":
        if extracted.exists():
            kitlib.rmtree(extracted)
        kitlib.safe_extract_zip(installer, extracted)
    else:
        raise KitError(f"{installer.name} is an .exe installer; only MSI and ZIP packages can be unpacked without installing.")
    root = engine_root(extracted, item["tool"])
    if root is None:
        raise KitError(f"{item['tool']} was not found after unpacking {installer.name}.")
    return root


def _engine_installed_copy(item: dict) -> Path | None:
    for variable in ("ProgramFiles", "ProgramW6432", "ProgramFiles(x86)", "LOCALAPPDATA"):
        base = os.environ.get(variable)
        if not base:
            continue
        bases = [Path(base)] + ([Path(base) / "Programs"] if variable == "LOCALAPPDATA" else [])
        for folder in bases:
            for pattern in item["installed"]:
                for candidate in sorted(folder.glob(pattern), reverse=True):
                    if (candidate / item["tool"]).is_file():
                        return candidate
    return None


def prepare_engine(name: str, item: dict, args) -> None:
    target = ENGINE_DIR / item["dest"]
    if (target / item["tool"]).is_file() and not args.clean:
        log(f"  [ready] {item['title']}")
        return
    log(f"  {item['title']}")
    manual = CACHE / "engines" / name
    errors = []
    root = None
    if (manual / item["tool"]).is_file():                       # an unpacked copy supplied by hand
        root = manual
        log(f"  using the unpacked copy in {manual}")
    if root is None and not args.offline:
        try:
            root = _engine_from_winget(name, item)
        except KitError as exc:
            errors.append(str(exc))
            log(f"  winget route failed: {exc}")
    if root is None:
        root = _engine_installed_copy(item)
        if root:
            log(f"  using the copy installed on this machine: {root}")
    if root is None:
        raise KitError(f"{item['title']} could not be prepared.\n"
                       + "\n".join("  " + e for e in errors)
                       + f"\n  Fix (any one): update winget (winget upgrade --id Microsoft.AppInstaller); or install {item['title'].split(' (')[0]} "
                         f"on this PC (it is then copied from Program Files); or unpack it into cache\\engines\\{name}; "
                         "or build without the engines: BUILD_NOP_SETUP.bat --no-engines")
    if target.exists():
        kitlib.rmtree(target)
    shutil.copytree(root, target)
    prune_engine(target, item.get("prune", []))
    size = sum(p.stat().st_size for p in target.rglob("*") if p.is_file())
    log(f"  ok  {name}: {kitlib.human_size(size)} -> converters\\{item['dest']}")


