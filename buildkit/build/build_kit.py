def lock_components() -> dict:
    return kitlib.load_json(CONFIG / "components.lock.json")


@step("Preflight checks")
def preflight(args):
    log(f"Kit folder : {KIT}")
    log(f"Python     : {sys.version.split()[0]} ({sys.executable})")
    if os.name != "nt":
        raise KitError("The installer can only be built on Windows 10/11 x64 (PyInstaller does not cross-compile).")
    if platform.machine().upper() not in {"AMD64", "X86_64"}:
        raise KitError(f"This kit builds for Windows x64; this machine is {platform.machine()}.")
    build = kitlib.windows_build()
    if build < MIN_BUILD:
        raise KitError(f"Windows build {build} is too old (need {MIN_BUILD}+: Windows 10 1809 / LTSC 2019 or newer).")
    if sys.version_info[:2] != (3, 13):
        raise KitError("The build must run on the private Python 3.13 provisioned by BUILD_NOP_SETUP.bat.")
    WORK.mkdir(exist_ok=True)
    free = kitlib.free_space_gb(WORK)
    log(f"Free space : {free:.1f} GB")
    if free < 8:
        raise KitError("At least 8 GB of free disk space is required for the build.")
    if len(str(KIT)) > 90:
        log("WARNING: the kit folder path is long. Move the folder closer to the drive root (for example C:\\NOP_Kit)"
            " if PyInstaller or Qt report path-length errors.")
    if any(part.lower() in {"onedrive", "dropbox", "yandex.disk"} for part in KIT.parts):
        log("WARNING: the kit is inside a cloud-synced folder; sync clients can lock files during the build.")
    if not SOURCE.is_file():
        raise KitError(f"Application source not found: {SOURCE}")


@step("Python packages (hash-locked)")
def install_requirements(args):
    lock = CONFIG / "requirements.lock"
    marker = WORK / "requirements.sha256"
    digest = kitlib.sha256_file(lock)
    if marker.is_file() and marker.read_text().strip() == digest and not args.clean:
        probe = subprocess.run([sys.executable, "-c", "import PyQt6.QtWidgets, yt_dlp, numpy, PIL, fitz, mutagen, PyInstaller"],
                               capture_output=True)
        if probe.returncode == 0:
            log("  packages already installed for this lock file")
            return
    if args.offline:
        raise KitError("Offline mode: packages are not installed yet and cannot be downloaded.")
    kitlib.run([sys.executable, "-m", "pip", "install", "--disable-pip-version-check", "--no-input", "--only-binary=:all:",
                "--require-hashes", "--no-deps", "--upgrade", "-r", str(lock)])
    kitlib.run([sys.executable, "-m", "pip", "check"])
    marker.write_text(digest)


