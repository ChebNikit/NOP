def _locked_requirement_versions() -> dict[str, str]:
    versions = {}
    requirement = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s\\]+)")
    for line in (CONFIG / "requirements.lock").read_text(encoding="utf-8").splitlines():
        match = requirement.match(line.strip())
        if match:
            versions[match.group(1).lower()] = match.group(2)
    return versions


def _pascal_lines(items: list[str]) -> str:
    """Format a list as a Pascal Script string expression with CRLF separators."""
    if not items:
        return "''"
    quoted = ["'" + item.replace("'", "''") + "'" for item in items]
    return (" + #13#10 +\n    ").join(quoted)


def write_inno_script(template_path: Path, output_path: Path) -> Path:
    """Write an Inno Setup script with exactly one UTF-8 BOM.

    The template is itself UTF-8-with-BOM. Reading it as plain UTF-8 would keep
    that marker as U+FEFF; writing with utf-8-sig would then prepend a second
    marker, which makes ISCC reject the first line as text outside a section.
    """
    source = template_path.read_text(encoding="utf-8-sig").lstrip("\ufeff")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(source, encoding="utf-8-sig")
    raw = output_path.read_bytes()
    bom = b"\xef\xbb\xbf"
    if not raw.startswith(bom) or raw.startswith(bom + bom):
        raise KitError("Generated Inno Setup script must contain exactly one UTF-8 BOM.")
    return output_path


