def apo_installer(args) -> Path:
    """Equalizer APO installer embedded into NOP_Setup.exe (system-wide equalizer). Pinned by SHA-256; a failure stops the build."""
    spec = lock_components()["installers"]["equalizer_apo"]
    target = CACHE / spec["file"]
    CACHE.mkdir(exist_ok=True)
    if args.offline and not target.is_file():
        raise KitError(f"Offline mode: {spec['file']} (Equalizer APO) is missing from the cache folder ({CACHE}). "
                       f"Download it from {spec['source']} and copy it there.")
    # SourceForge answers some clients with 403 or with an HTML page, so several addresses and client names are tried.
    # Every attempt is checked against the pinned SHA-256: a wrong or HTML file is never used.
    curl, wget = "curl/8.5.0", "Wget/1.21.4"
    attempts = [(spec["source"], curl), (spec["url"], curl), (spec["url"], wget)]
    attempts += [(mirror, curl) for mirror in spec.get("mirror_urls", [])]
    attempts += [(spec["url"], kitlib.BROWSER_AGENT), (spec["source"], kitlib.BROWSER_AGENT)]
    errors = []
    for url, agent in attempts:
        try:
            return kitlib.download(url, target, spec["sha256"], spec.get("size"), retries=1,
                                   label=f"Equalizer APO {spec['version']}", user_agent=agent)
        except KitError as exc:
            errors.append(f"  {url} as {agent.split('/')[0]}: {str(exc)[:220]}")
            log("      failed, trying another way")
    raise KitError(f"Equalizer APO {spec['version']} could not be prepared. Attempts:\n" + "\n".join(errors) + "\n"
                   f"Download {spec['file']} in a browser from {spec['source']}, copy it to {CACHE}, and run the build again. "
                   f"Its SHA-256 must be {spec['sha256']} (certutil -hashfile <file> SHA256).")


