def _find_iscc() -> Path | None:
    """Find the selected compiler across separate build invocations.

    NOP_ISCC set by step 9 only lives in that Python process. When the user resumes
    directly at step 10, rediscover an already-installed compiler via PATH/registry/
    standard install folders instead of requiring step 9 to run again.
    """
    env = os.environ.get("NOP_ISCC")
    if env and Path(env).is_file():
        return Path(env)
    candidate = INNO_DIR / "ISCC.exe"
    if candidate.is_file():
        return candidate
    minimum = lock_components()["signed_downloads"]["innosetup"]["min_version"]
    return _accept_existing_iscc(minimum)


def _registry_inno_folders() -> list[Path]:
    """Install folders of every 'Inno Setup*' entry in the uninstall registry (HKCU, HKLM, WOW6432Node)."""
    try:
        import winreg
    except ImportError:
        return []
    folders = []
    base = r"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall"
    for hive in (winreg.HKEY_CURRENT_USER, winreg.HKEY_LOCAL_MACHINE):
        for view in (winreg.KEY_WOW64_64KEY, winreg.KEY_WOW64_32KEY):
            try:
                root = winreg.OpenKey(hive, base, 0, winreg.KEY_READ | view)
            except OSError:
                continue
            with root:
                index = 0
                while True:
                    try:
                        name = winreg.EnumKey(root, index)
                    except OSError:
                        break
                    index += 1
                    if not name.lower().startswith("inno setup"):
                        continue
                    try:
                        with winreg.OpenKey(root, name) as key:
                            for value in ("InstallLocation", "Inno Setup: App Path"):
                                try:
                                    text = str(winreg.QueryValueEx(key, value)[0]).strip().strip('"')
                                except OSError:
                                    continue
                                if text:
                                    folders.append(Path(text))
                    except OSError:
                        continue
    return folders


def installed_iscc_candidates() -> list[Path]:
    """Inno Setup already present on the machine: PATH, registry, and any 'Inno Setup*' folder in the usual roots."""
    found: list[Path] = []

    def add(path: Path) -> None:
        if path.is_file() and path not in found:
            found.append(path)

    on_path = shutil.which("ISCC")
    if on_path:
        add(Path(on_path))
    for folder in _registry_inno_folders():
        add(folder / "ISCC.exe")
    roots = []
    for name in ("LOCALAPPDATA", "ProgramFiles", "ProgramFiles(x86)", "ProgramW6432"):
        value = os.environ.get(name)
        if value:
            roots.append(Path(value))
            roots.append(Path(value) / "Programs")
    for root in roots:
        try:
            for path in sorted(root.glob("Inno Setup*/ISCC.exe"), reverse=True):  # newest-looking name first
                add(path)
        except OSError:
            continue
    return found


def version_tuple(text: str) -> tuple:
    return tuple(int(part) for part in re.findall(r"\d+", text)[:3])


def inno_urls(spec: dict, tags_html: str = "") -> list[str]:
    """Return valid GitHub release assets for Inno Setup 6, newest first."""
    versions = list(spec.get("preferred_versions", []))
    found = sorted({tuple(map(int, m)) for m in re.findall(r"is-(\d+)_(\d+)_(\d+)(?![\d_])", tags_html)}, reverse=True)
    newest_six = next((v for v in found if v[0] == 6), None)
    if newest_six:
        discovered = ".".join(map(str, newest_six))
        if discovered not in versions:
            versions.append(discovered)

    minimum = version_tuple(spec.get("min_version", "0"))
    urls = []
    seen = set()
    for version in versions:
        if version_tuple(version) < minimum:
            continue
        tag = "is-" + version.replace(".", "_")
        for template in spec.get("url_templates", []):
            url = template.format(major=version.split(".")[0], version=version, tag=tag)
            if url not in seen:
                seen.add(url)
                urls.append(url)
    return urls


def _file_version(path: Path) -> str:
    """ProductVersion of an executable (empty string when it cannot be read)."""
    try:
        result = subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command",
                                 "$v=(Get-Item -LiteralPath $env:NOP_KIT_PATH).VersionInfo; if ($v.ProductVersion) {$v.ProductVersion} else {$v.FileVersion}"],
                                capture_output=True, text=True, timeout=60, env={**os.environ, "NOP_KIT_PATH": str(path)})
    except (OSError, subprocess.SubprocessError):
        return ""
    return result.stdout.strip()


def inno_version(iscc: Path, read_version=None) -> tuple:
    """Installed Inno Setup version as a tuple, (0,) when unknown.

    ISCC.exe itself carries version 0.0.0.0, so the real version is read from the compiler DLL / wizard
    executables next to it; as a last resort the major number comes from the folder name ('Inno Setup 6')."""
    read_version = read_version or _file_version
    for name in ("ISCmplr.dll", "Compil32.exe", "Setup.exe", "ISCC.exe"):
        candidate = Path(iscc).parent / name
        if candidate.is_file():
            version = version_tuple(read_version(candidate))
            if version and any(version):
                return version
    match = re.search(r"Inno Setup (\d+)", str(Path(iscc).parent.name))
    return (int(match.group(1)),) if match else (0,)


def _accept_existing_iscc(minimum: str) -> Path | None:
    """Use an installed Inno 6 compiler; accept major-only metadata and verify compatibility at compile time."""
    minimum_version = version_tuple(minimum)
    for path in installed_iscc_candidates():
        version = inno_version(path)
        shown = ".".join(map(str, version))
        # Some installs expose only the folder name ("Inno Setup 6"). Do not reject
        # those: the script has a pre-6.6 fallback, and the compiler itself validates it.
        accepted = version[0] >= 6 and (len(version) == 1 or version >= minimum_version)
        if accepted:
            note = " (minor version unavailable; compiler compatibility will be checked)" if len(version) == 1 else ""
            log(f"  found installed Inno Setup {shown}: {path}{note}")
            return path
        log(f"  ignoring Inno Setup {shown} (need {minimum} or newer): {path}")
    return None


