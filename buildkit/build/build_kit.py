def validate_source(path: Path) -> str:
    """Checks that a (possibly modified) NOP source still has everything the installer relies on; returns its version."""
    text = Path(path).read_text(encoding="utf-8")
    try:
        ast.parse(text)
    except SyntaxError as exc:
        raise KitError(f"{Path(path).name} has a syntax error at line {exc.lineno}: {exc.msg}") from None
    missing = [f"  {name}  ({why})" for name, why in REQUIRED_HOOKS.items() if name not in text]
    if missing:
        raise KitError(f"{Path(path).name} lacks parts the installer needs. Base your changes on source\\NOP_1_2.py and keep:\n"
                       + "\n".join(missing))
    match = re.search(r'^APP_VERSION\s*=\s*"([^"]+)"', text, re.M)
    if not match:
        raise KitError('APP_VERSION = "x.y" was not found in the NOP source.')
    return match.group(1)

def media_extensions(source: Path) -> list[str]:
    """MEDIA_EXTS literal from the NOP source (no import of the application)."""
    tree = ast.parse(Path(source).read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "MEDIA_EXTS" for t in node.targets):
            return sorted(ast.literal_eval(node.value))
    raise KitError("MEDIA_EXTS was not found in the NOP source.")


